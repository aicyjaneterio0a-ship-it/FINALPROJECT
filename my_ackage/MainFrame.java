    private void btnSortNameActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSortNameActionPerformed
        DefaultTableModel model =
        (DefaultTableModel) tableClients.getModel();

        TableRowSorter<DefaultTableModel> sorter =
        new TableRowSorter<>(model);

        tableClients.setRowSorter(sorter);

        // Sort NAME column A-Z
        sorter.setSortKeys(
            java.util.Collections.singletonList(
                new RowSorter.SortKey(
                    0,
                    javax.swing.SortOrder.ASCENDING
                )
            )
        );

        sorter.sort();
    }//GEN-LAST:event_btnSortNameActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        int row = tableClients.getSelectedRow();

        if (row < 0) {
            JOptionPane.showMessageDialog(this,
                "No row is selected! Please select one row",
                "select row",
                JOptionPane.ERROR_MESSAGE);
        } else  {
            DefaultTableModel model = (DefaultTableModel) tableClients.getModel();
            model.removeRow(row);
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

