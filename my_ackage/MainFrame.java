    private void btnApprovedActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnApprovedActionPerformed
        String name = tfName.getText();
        String email = tfYearLevel.getText();
        String phone = tfSchoolId.getText();
        String address = tfAddress.getText();

        if (name.isEmpty() || email.isEmpty() || phone.isEmpty() || address.isEmpty()) {

            JOptionPane.showMessageDialog(this, "Please enter all fields", "Try again", JOptionPane.ERROR_MESSAGE);

        } else {
            DefaultTableModel model = (DefaultTableModel) tableClients.getModel();
            model.addRow(new Object[] {name, email, phone, address});

            tfName.setText("");
            tfYearLevel.setText("");
            tfSchoolId.setText("");
            tfAddress.setText("");

        }

    }//GEN-LAST:event_btnApprovedActionPerformed

